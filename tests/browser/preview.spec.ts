import { test, expect } from '@playwright/test'
test('preview: schedule, reload, simulate exactly once, read and cancel', async ({ page }) => {
  await page.goto('/teste/dicas')
  await page.getByLabel('Título', { exact: true }).fill('Dica PR2')
  await page.getByLabel('Mensagem', { exact: true }).fill('Teste de agendamento da central.')
  await page.getByLabel('Disponível para envio a partir de').fill('2030-01-01T10:00')
  await page.getByRole('button', { name: 'Agendar envio', exact: true }).click()
  await expect(page.getByText('Agendado · Dica')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Agendado · Dica')).toBeVisible()
  await page.getByRole('button', { name: 'Simular rodada de envio' }).click()
  await expect(page.getByRole('heading', { name: 'Caixa de teste · 1 não lidas' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Simular rodada de envio' })).toBeDisabled()
  await page.getByRole('button', { name: 'Marcar como lida' }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Caixa de teste · 0 não lidas' })).toBeVisible()
  await page.getByLabel('Título', { exact: true }).fill('Cancelar PR2')
  await page.getByLabel('Mensagem', { exact: true }).fill('Não deve ser enviada.')
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByText('Cancelado · Dica')).toBeVisible()
})
test('cron and admin endpoints reject requests without authorization', async ({ request }) => {
  expect((await request.get('/api/cron/tips')).status()).toBe(401)
  const disabled = await request.get('/api/cron/tips', { headers: { Authorization: 'Bearer local-test-only-secret' } })
  expect(await disabled.json()).toEqual({ enabled: false, delivered: 0 })
  expect((await request.get('/api/tips')).status()).toBe(401)
  expect((await request.get('/api/notifications')).status()).toBe(401)
})
